/**
 * Regenerates ../metrics.ts: the advance width of every character the charts draw, measured in Chromium from the
 * site's own font files (public/fonts). The drawer lays text out with these tables instead of a canvas, so the
 * server and the browser compute the same layout and the server-rendered SVG matches the client redraw.
 *
 *   npx tsx src/app/research-v11/charts/tools/measure-fonts.ts
 *
 * Not imported by the app.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { chromium } from "playwright";

const ROOT = resolve(__dirname, "../../../../..");
const FONTS = join(ROOT, "public/fonts");
const OUT = resolve(__dirname, "../metrics.ts");

const FACES = {
  sans400: { family: "Satoshi", file: "Satoshi-Regular.woff2", weight: 400 },
  sans500: { family: "Satoshi", file: "Satoshi-Medium.woff2", weight: 500 },
  sans700: { family: "Satoshi", file: "Satoshi-Bold.woff2", weight: 700 },
  fig500: {
    family: "Neue Montreal",
    file: "NeueMontreal-Medium.woff2",
    weight: 500,
  },
} as const;

const EXTRA = "’‘“”×·–—…éèêëüöäåñçßáíóúàâîôûœæøÉÜÖÄÅ€£°±→≥≤½";
const CHARS =
  Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join("") +
  EXTRA;

async function main() {
  const css = Object.values(FACES)
    .map(
      (f) =>
        `@font-face{font-family:"${f.family}";src:url(data:font/woff2;base64,${readFileSync(join(FONTS, f.file)).toString("base64")}) format("woff2");font-weight:${f.weight};}`,
    )
    .join("\n");
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.setContent(`<!doctype html><style>${css}</style><body></body>`);
  const result = await page.evaluate(
    async ({ faces, chars }) => {
      const out: Record<string, number[]> = {};
      // spans, not a canvas, so the charts' tabular figures (font-variant-numeric: tabular-nums) are what is measured
      const span = document.createElement("span");
      span.style.cssText =
        "position:absolute;white-space:pre;font-variant-numeric:tabular-nums;font-kerning:none;font-size:1000px";
      document.body.appendChild(span);
      for (const [key, f] of Object.entries(faces)) {
        await document.fonts.load(`${f.weight} 100px "${f.family}"`);
        span.style.fontFamily = `"${f.family}"`;
        span.style.fontWeight = String(f.weight);
        // an array in METRIC_CHARS order: an object keyed by character would put the digits first
        out[key] = Array.from(chars).map((ch) => {
          span.textContent = ch;
          return Math.round(span.getBoundingClientRect().width * 10) / 10;
        });
      }
      return out;
    },
    { faces: FACES, chars: CHARS },
  );
  await browser.close();
  const body = Object.entries(result)
    .map(([k, m]) => `  ${k}: ${JSON.stringify(m)},`)
    .join("\n");
  writeFileSync(
    OUT,
    `/* Generated by tools/measure-fonts.ts from public/fonts (${new Date().toISOString().slice(0, 10)}). Do not edit.
   Advance widths in thousandths of an em, one per character of METRIC_CHARS, in that order. */
export const METRIC_CHARS = ${JSON.stringify(CHARS)};
export const METRICS: Record<'sans400' | 'sans500' | 'sans700' | 'fig500', number[]> = {
${body}
};
`,
  );
  console.log(`wrote ${OUT}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
